-- ผลที่คาดหวัง: แสดงรายการใบแจ้งหนี้ที่ยังค้างจ่ายหรือจ่ายบางส่วนทั้งหมดในตาราง เช่น INV-2026-0002, INV-2026-0003, INV-2026-0007, INV-2026-0008, INV-2026-0011, INV-2026-0015, INV-2026-0017, INV-2026-0020
-- คำอธิบาย: ช่วยให้พนักงานฝ่ายการเงินสามารถดึงรายการใบแจ้งหนี้ที่ต้องติดตามหนี้สินหรือตรวจสอบยอดการค้างชำระได้อย่างรวดเร็ว

-- ข้อ 2.5 BETWEEN
-- คำถาม: ดึงรายการชำระเงิน (Payments) ที่มียอดชำระเงิน (amount_paid) ในช่วงระหว่าง 500 บาท ถึง 2,000 บาท เพื่อตรวจสอบระดับการใช้จ่ายปานกลางของผู้ป่วย
SELECT 
    payment_number AS "รหัสชำระเงิน", 
    invoice_id AS "รหัสใบแจ้งหนี้", 
    payment_method AS "วิธีการชำระ", 
    amount_paid AS "ยอดที่จ่าย", 
    paid_at AS "เวลาชำระเงิน"
FROM payments 
WHERE amount_paid BETWEEN 500.00 AND 2000.00;
-- ผลที่คาดหวัง: รายการชำระเงินที่มียอดเงินอยู่ในช่วง 500 ถึง 2000 บาท เช่น PAY-2026-0001, PAY-2026-0002, PAY-2026-0004, PAY-2026-0005, PAY-2026-0007, PAY-2026-0008, PAY-2026-0011, PAY-2026-0014, PAY-2026-0015, PAY-2026-0016, PAY-2026-0017
-- คำอธิบาย: ค้นหาข้อมูลยอดชำระเงินระดับปานกลางเพื่อวิเคราะห์แนวโน้มยอดเงินชำระเฉลี่ยผ่านช่องทางต่างๆ ของโรงพยาบาล

-- ข้อ 2.6 DISTINCT
