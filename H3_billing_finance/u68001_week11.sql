-- ข้อ 6.1 ตรวจค่าที่หายไป (IS NULL)
-- คำถาม: ตรวจสอบตารางการชำระเงิน (payments) ว่ามีแถวรายการใดบ้างที่ไม่มีหมายเลขอ้างอิงการทำธุรกรรม (transaction_ref IS NULL) เพื่อแยกว่ารายการไหนเป็นการชำระด้วยเงินสดที่หน้าร้านแคชเชียร์
SELECT 
    payment_number AS "รหัสชำระเงิน", 
    invoice_id AS "รหัสใบแจ้งหนี้", 
    payment_method AS "วิธีการชำระ", 
    amount_paid AS "จำนวนเงินสุทธิ"
FROM payments 
WHERE transaction_ref IS NULL;
-- ผลที่คาดหวัง: รายการชำระเงินที่จ่ายด้วย CASH ทั้งหมด ซึ่งระบบจะแสดงค่า transaction_ref เป็น NULL หรือว่างเปล่า
-- คำอธิบาย: คิวรีนี้ใช้กรองและตรวจสอบประวัติการชำระเงินสดในแคชเชียร์เพื่อนำไปนับเงินและสรุปบัญชีรอบวันทำงาน

-- ข้อ 6.2 ตรวจข้อมูลซ้ำ
-- คำถาม: ตรวจสอบว่าในตารางรายการบริการโรงพยาบาล (billing_services) มีรายการที่รหัสค่าบริการ (service_code) ซ้ำซ้อนกันในฐานข้อมูลหรือไม่
SELECT 
    service_code AS "รหัสค่าบริการทางการแพทย์", 
    COUNT(*) AS "จำนวนแถวที่ซ้ำซ้อน"
FROM billing_services
GROUP BY service_code
HAVING COUNT(*) > 1;
-- ผลที่คาดหวัง: แสดงตารางเปล่า (ว่าง) ซึ่งยืนยันว่าไม่มีข้อมูลรหัสบริการที่ซ้ำกันเลยในระบบ (มี duplicate_count = 0) สอดคล้องกับคีย์หลัก UNIQUE
-- คำอธิบาย: ช่วยตรวจสอบความสมบูรณ์ของคุณภาพข้อมูลตารางเพื่อหลีกเลี่ยงข้อมูลบริการซ้ำซ้อนที่เกิดจากมนุษย์ป้อนข้อมูลผิดพลาด

-- ข้อ 6.3 เสนอแนวทางแก้ไข (ใช้ Transaction block BEGIN ... ROLLBACK)
-- คำถาม: หากต้องการทดลองแก้ไขปัญหาปรับปรุงราคาค่าบริการในตาราง และหลีกเลี่ยงผลกระทบต่อข้อมูลจริงในอนาคต ให้เขียนทดสอบด้วยการเปิด Transaction บันทึกข้อมูลและยกเลิกงาน (Rollback) เพื่อความปลอดภัย
BEGIN;

-- 1. แสดงราคาเดิมก่อนแก้ไข
SELECT service_code, service_name, unit_price 
FROM billing_services 
WHERE service_code = 'SVC-RM-01';

-- 2. เสนอทางแก้ไขโดยใช้คำสั่ง UPDATE ปรับราคาห้องพักจาก 2,500 บาท เป็น 2,800 บาท
UPDATE billing_services 
SET unit_price = 2800.00 
WHERE service_code = 'SVC-RM-01';

-- 3. เรียกดูผลลัพธ์จำลองราคาใหม่หลังปรับปรุงเพื่อตรวจสอบความถูกต้อง
SELECT service_code, service_name, unit_price 
FROM billing_services 
WHERE service_code = 'SVC-RM-01';

-- 4. ย้อนกลับคำสั่งเพื่อไม่ให้บันทึกจริง ป้องกันข้อมูลหลักเสียหาย
ROLLBACK;

-- 5. ตรวจสอบยืนยันราคาห้องพักหลังจากยกเลิกรายการ ว่าราคายังเป็น 2,500 บาทเหมือนเดิม
SELECT service_code, service_name, unit_price 
FROM billing_services 
WHERE service_code = 'SVC-RM-01';
-- ผลที่คาดหวัง: แสดงราคาเดิม (2500.00) -> ราคาหลังอัปเดต (2800.00) -> ราคาหลังยกเลิก ROLLBACK (2500.00) ตามลำดับ เพื่อยืนยันว่าการแก้ไขทำงานชั่วคราว
-- คำอธิบาย: แสดงวิธีการแก้ไขจุดผิดปกติข้อมูลอย่างปลอดภัยภายใน Transaction Block เพื่อให้นักเรียนเข้าใจกระบวนการรันสคริปต์ในระบบงานจริง
