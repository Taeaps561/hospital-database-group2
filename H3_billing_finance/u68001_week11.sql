-- ข้อ 2.2 WHERE และ Operators
-- คำถาม: ค้นหาข้อมูลใบแจ้งหนี้ที่มียอดเงินสุทธิ (net_amount) มากกว่า 1,000 บาท และมีสถานะชำระเงินเรียบร้อยแล้ว ('PAID') เท่านั้น
SELECT 
    invoice_number AS "เลขที่ใบแจ้งหนี้", 
    patient_id AS "รหัสผู้ป่วย", 
    net_amount AS "ยอดสุทธิ", 
    status AS "สถานะ"
FROM invoices 
WHERE status = 'PAID' AND net_amount > 1000.00;
-- ผลที่คาดหวัง: แสดงรายการใบแจ้งหนี้ที่มีสถานะเป็น 'PAID' และมียอดสุทธิเกิน 1000 บาท ได้แก่ INV-2026-0005, INV-2026-0009, INV-2026-0014, INV-2026-0018
-- คำอธิบาย: ใช้คัดกรองใบแจ้งหนี้ที่ชำระเงินเรียบร้อยและมียอดใช้จ่ายสูง เพื่อนำมาทำสถิติลูกค้ากลุ่มเป้าหมายที่มีกำลังจ่าย

-- ข้อ 2.3 LIKE
-- คำถาม: ค้นหารายชื่อค่าบริการในระบบที่เป็นกลุ่มค่ายา โดยค้นหาจากรหัสบริการที่มีคำว่า 'MED' หรือชื่อบริการที่มีคำว่า 'ยา'
SELECT 
    service_code AS "รหัสบริการ", 
    service_name AS "ชื่อบริการ", 
    category AS "หมวดหมู่", 
