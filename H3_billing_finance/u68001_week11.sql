FROM billing_services 
WHERE service_code LIKE '%MED%' OR service_name LIKE '%ยา%';
-- ผลที่คาดหวัง: แสดงรายชื่อยา 5 รายการ (SVC-MED-01, SVC-MED-02, SVC-MED-03, SVC-MED-04, SVC-MED-05) พร้อมราคาสินค้าค่ายา
-- คำอธิบาย: คำสั่งนี้ใช้ค้นหารายการที่เกี่ยวข้องกับยาจากแค็ตตาล็อกค่าบริการทั้งหมดของโรงพยาบาล เพื่อจัดหมวดหมู่ค่ายา

-- ข้อ 2.4 IN
-- คำถาม: ค้นหาใบแจ้งหนี้ที่มีปัญหาค้างจ่ายหรือยอดเงินผิดปกติ ได้แก่ ใบแจ้งหนี้ที่ยังมีสถานะเป็น 'UNPAID' (ยังไม่ชำระ), 'PARTIALLY_PAID' (ชำระบางส่วน) หรือ 'CANCELLED' (ยกเลิก)
SELECT 
    invoice_number AS "เลขที่ใบแจ้งหนี้", 
    patient_id AS "รหัสผู้ป่วย", 
    net_amount AS "ยอดสุทธิ", 
    status AS "สถานะใบแจ้งหนี้"
FROM invoices 
