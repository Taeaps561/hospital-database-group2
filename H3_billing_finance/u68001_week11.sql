-- ข้อ 3.1 ORDER BY และ LIMIT
-- คำถาม: แสดงข้อมูลใบแจ้งหนี้ที่มียอดเงินสุทธิ (net_amount) สูงที่สุด 5 อันดับแรกของโรงพยาบาล
SELECT 
    invoice_number AS "เลขที่ใบแจ้งหนี้", 
    patient_id AS "รหัสผู้ป่วย", 
    net_amount AS "ยอดสุทธิสูงที่สุด", 
    status AS "สถานะ"
FROM invoices 
ORDER BY net_amount DESC 
LIMIT 5;
-- ผลที่คาดหวัง: ใบแจ้งหนี้ 5 รายการแรกที่มียอดสูงสุด (เช่น ยอด 3,120.00, 3,000.00, 3,000.00, 3,000.00, 2,800.00) เรียงตามลำดับจากมากไปน้อย
-- คำอธิบาย: ใช้ค้นหาเคสผู้ป่วยที่มียอดรักษาพยาบาลสูงสุด 5 เคสแรก เพื่อเตรียมวิเคราะห์ระดับค่ารักษาพยาบาลของผู้ป่วยใน (IPD)

-- ข้อ 3.2 MIN และ MAX
-- คำถาม: ค้นหาราคาต่อหน่วยที่ถูกที่สุดและแพงที่สุดในตารางรายการค่าบริการโรงพยาบาล (billing_services)
SELECT 
    MIN(unit_price) AS "ค่าบริการที่ถูกที่สุด (บาท)", 
    MAX(unit_price) AS "ค่าบริการที่แพงที่สุด (บาท)"
FROM billing_services;
-- ผลที่คาดหวัง: ผลลัพธ์แสดง 30.00 บาท (ยาแก้แพ้ CPM) เป็นค่าบริการต่ำสุด และ 2500.00 บาท (ค่าห้องพักผู้ป่วย) เป็นค่าบริการสูงสุด
-- คำอธิบาย: ใช้ประเมินขอบเขตของราคาบริการในโรงพยาบาล เพื่อดูความแตกต่างของราคาในแค็ตตาล็อกสินค้าและบริการทั้งหมด

-- ข้อ 3.3 COUNT
-- คำถาม: นับจำนวนรายการยื่นเคลมประกันในตาราง insurance_claims ทั้งหมดที่ยังรอการพิจารณาตรวจสอบอนุมัติอยู่ (claim_status = 'PENDING')
SELECT COUNT(*) AS "จำนวนรายการเคลมประกันที่ค้างอยู่"
FROM insurance_claims 
WHERE claim_status = 'PENDING';
-- ผลที่คาดหวัง: แสดงจำนวนยอดเคสเคลมประกันที่ยังค้างพิจารณา (ปัจจุบันมี 0 เนื่องจากยังไม่ใส่เคลมรออนุมัติเพิ่มเติม หรือข้อมูลเดิมถูก Approve ไปหมดแล้ว)
-- คำอธิบาย: คิวรีนี้ช่วยตรวจสอบปริมาณงานเคลมที่ค้างชำระ เพื่อแจ้งเตือนพนักงานบัญชีให้ส่งข้อมูลประกันเพิ่ม

-- ข้อ 3.4 SUM
-- คำถาม: สรุปยอดรวมจำนวนเงินที่ได้รับการอนุมัติจ่ายจริงจากบริษัทประกันภัย (approved_amount) จากรายการเคลมทั้งหมด
SELECT SUM(approved_amount) AS "ยอดรวมเงินเคลมที่ได้รับอนุมัติแล้ว (บาท)"
FROM insurance_claims 
WHERE claim_status = 'APPROVED';
-- ผลที่คาดหวัง: ยอดผลรวมอนุมัติจากประกันเท่ากับ 2530.00 บาท (2000.00 จากสัญญารายแรก และ 530.00 จากสัญญารายที่สอง)
-- คำอธิบาย: ใช้คำนวณยอดเงินรวมที่โรงพยาบาลได้รับชำระจากบริษัทคู่ค้าประกันภัยมาแล้ว เพื่อสรุปยอดรายรับในแผนกประกัน

-- ข้อ 3.5 AVG
-- คำถาม: ยอดคำนวณราคาเฉลี่ยรวมส่วนลดของใบแจ้งหนี้ (net_amount) ทั้งหมดในระบบ เพื่อตรวจสอบค่าใช้จ่ายต่อบิลโดยเฉลี่ยของผู้ใช้บริการ
SELECT ROUND(AVG(net_amount), 2) AS "ยอดรวมบิลเฉลี่ยต่อผู้ป่วย (บาท)"
FROM invoices;
-- ผลที่คาดหวัง: ค่าเฉลี่ยคำนวณได้อยู่ที่ประมาณ 1251.43 บาท จากยอดบิลทั้งหมด 21 บิล
-- คำอธิบาย: ใช้สำหรับวิเคราะห์พฤติกรรมการจ่ายเงินเฉลี่ยต่อการเข้ามาใช้บริการของผู้ป่วย เพื่อนำไปวางแผนกลยุทธ์บริการและส่วนลด

-- ข้อ 3.6 CASE
-- คำถาม: จัดระดับใบแจ้งหนี้ตามระดับยอดเงินสุทธิเพื่อแยกวิเคราะห์กลุ่มผู้ป่วย โดยแบ่งออกเป็น 'High Charge' (ยอดเงินมากกว่า 2,000 บาท), 'Medium Charge' (ยอดเงินตั้งแต่ 500 ถึง 2,000 บาท) และ 'Low Charge' (ยอดเงินต่ำกว่า 500 บาท)
SELECT 
    invoice_number AS "เลขที่ใบแจ้งหนี้", 
    net_amount AS "ยอดสุทธิ",
    CASE 
        WHEN net_amount > 2000.00 THEN 'High Charge (ยอดสูง)'
        WHEN net_amount BETWEEN 500.00 AND 2000.00 THEN 'Medium Charge (ยอดปานกลาง)'
        ELSE 'Low Charge (ยอดต่ำ)'
    END AS "ระดับค่ารักษา"
FROM invoices
ORDER BY net_amount DESC;
-- ผลที่คาดหวัง: รายการใบแจ้งหนี้แสดงประเภทระดับค่ารักษาอย่างชัดเจนสอดคล้องตามเกณฑ์เงื่อนไขยอดเงิน 3 ระดับ
-- คำอธิบาย: คิวรีนี้ช่วยวิเคราะห์สัดส่วนระดับยอดบิลชำระของผู้ป่วยในระบบการเงิน เพื่อจัดกลุ่มการตลาดโรงพยาบาล


-- ============================================================================
-- ส่วนที่ 4 GROUP BY และ HAVING — 4 คะแนน
-- ============================================================================

-- ข้อ 4.1 GROUP BY
-- คำถาม: สรุปจำนวนครั้งที่มีการชำระเงินและยอดเงินชำระรวม (SUM amount_paid) แยกตามประเภทช่องทางการชำระเงิน (payment_method) เพื่อดูความนิยมของแต่ละช่องทาง
SELECT 
    payment_method AS "วิธีการชำระเงิน", 
    COUNT(*) AS "จำนวนครั้งที่ใช้งาน",
    SUM(amount_paid) AS "ยอดชำระรวมทั้งหมด (บาท)"
FROM payments
GROUP BY payment_method
ORDER BY SUM(amount_paid) DESC;
-- ผลที่คาดหวัง: ตารางสรุปยอดการจ่ายเงินตามช่องทาง เช่น CASH, PROMPTPAY, CREDIT_CARD โดยระบุความถี่และยอดเงินรวมของแต่ละช่องทาง
-- คำอธิบาย: แสดงข้อมูลสถิติช่องทางที่ผู้ป่วยนิยมชำระเงินมากที่สุด เพื่อช่วยเพิ่มประสิทธิภาพระบบจ่ายเงินของแคชเชียร์

-- ข้อ 4.2 HAVING
-- คำถาม: คัดเลือกหมวดค่าบริการ (category) ในตาราง billing_services ที่มีรายการบริการในหมวดนั้นตั้งแต่ 3 รายการขึ้นไป และแสดงราคาเฉลี่ยต่อชิ้น
SELECT 
    category AS "หมวดหมู่ค่าบริการ", 
    COUNT(*) AS "จำนวนรายการย่อย",
    ROUND(AVG(unit_price), 2) AS "ราคาเฉลี่ย (บาท)"
FROM billing_services
GROUP BY category
HAVING COUNT(*) >= 3;
-- ผลที่คาดหวัง: คัดกรองและแสดงเฉพาะหมวดหมู่ LABORATORY และ PHARMACY ที่มีรายการตรวจและยารวมกันในตารางตั้งแต่ 3 รายการขึ้นไป
-- คำอธิบาย: ใช้กรองกลุ่มค่าธรรมเนียมที่มีจำนวนรายการบริการหลากหลายในแค็ตตาล็อก เพื่อนำมาปรับปรุงโครงสร้างราคาส่วนลด

-- นักศึกษาต้องอธิบายความแตกต่างระหว่าง WHERE และ HAVING
/*
ความแตกต่างระหว่าง WHERE และ HAVING ในภาษา SQL:
1. WHERE clause: จะใช้กรองแถวข้อมูลดิบ (raw rows) "ก่อน" ที่จะนำข้อมูลเหล่านั้นมารวมกลุ่มด้วยคำสั่ง GROUP BY หรือทำ Aggregate คิวรีนี้ใช้ประมวลผลความเร็วได้ดีเนื่องจากตัดข้อมูลที่ไม่ต้องการออกก่อน จึงห้ามใช้ฟังก์ชัน Aggregate (เช่น COUNT, SUM, AVG) ภายใต้เงื่อนไข WHERE โดยตรง
2. HAVING clause: จะใช้กรองแถวผลลัพธ์ย่อย "หลังจาก" ที่ข้อมูลผ่านกระบวนการ GROUP BY มารวมกลุ่มเรียบร้อยแล้ว มักจะนำมาใช้ร่วมกับฟังก์ชันสรุปข้อมูล (Aggregate Functions) เพื่อตรวจสอบคุณสมบัติของกลุ่มนั้นๆ เช่น คัดเฉพาะกลุ่มที่มียอดผลรวมเกินเป้าหมาย เป็นต้น
*/


