-- ข้อ 5.1 INNER JOIN
-- คำถาม: ดึงรายการชำระเงิน (Payments) เชื่อมโยงกับใบแจ้งหนี้หลัก (Invoices) เพื่อแสดงชื่อเลขที่ชำระเงิน เลขที่ใบแจ้งหนี้ รหัสผู้ป่วย ยอดชำระเงิน และวันเวลาที่จ่ายเงิน
SELECT 
    p.payment_number AS "เลขที่การชำระเงิน", 
    i.invoice_number AS "เลขที่ใบแจ้งหนี้", 
    i.patient_id AS "รหัสผู้ป่วย", 
    p.payment_method AS "วิธีชำระเงิน", 
    p.amount_paid AS "จำนวนเงินที่ชำระ (บาท)", 
    p.paid_at AS "วันเวลาที่ชำระเงิน"
FROM payments p
INNER JOIN invoices i ON p.invoice_id = i.invoice_id
ORDER BY p.payment_number;
-- ผลที่คาดหวัง: แสดงข้อมูลแถวเชื่อมโยงที่มีข้อมูลความสัมพันธ์ตรงกันครบถ้วนทั้งสองตารางรวม 20 รายการชำระเงิน
-- คำอธิบาย: คิวรีนี้ช่วยตรวจสอบการจ่ายเงินคู่กับเลขใบแจ้งหนี้เพื่อระบุว่าเงินก้อนนี้จ่ายเข้ามาเพื่อปิดหนี้ใบไหน

-- ข้อ 5.2 LEFT JOIN
-- คำถาม: ดึงรายการใบแจ้งหนี้ (Invoices) ทั้งหมดที่มีในระบบ พร้อมข้อมูลการชำระเงิน (Payments) ที่เคยชำระเข้ามา แม้ว่าใบแจ้งหนี้นั้นจะยังไม่เคยถูกจ่ายเงินเลยก็ตาม (จะแสดงค่าชำระเงินเป็น NULL)
SELECT 
    i.invoice_number AS "เลขที่ใบแจ้งหนี้", 
    i.patient_id AS "รหัสผู้ป่วย", 
    i.net_amount AS "ยอดสุทธิของบิล", 
    i.status AS "สถานะใบแจ้งหนี้", 
    p.payment_number AS "เลขที่ชำระเงิน", 
    p.amount_paid AS "จำนวนเงินชำระ"
FROM invoices i
LEFT JOIN payments p ON i.invoice_id = p.invoice_id
ORDER BY i.invoice_number;
-- ผลที่คาดหวัง: รายชื่อใบแจ้งหนี้ทั้งหมด 21 ใบ โดยใบแจ้งหนี้ที่ยังไม่ได้จ่ายเงินเลย (เช่น INV-2026-0002, INV-2026-0003, INV-2026-0007, INV-2026-0011) จะแสดงฝั่งตาราง payments เป็นค่าว่าง (NULL)
-- คำอธิบาย: แสดงสถานะใบแจ้งหนี้ทั้งหมดคู่กับประวัติธุรกรรมเพื่อให้นักวิเคราะห์ตรวจสอบสัดส่วนผู้ป่วยจ่ายเงินสดเทียบกับเครดิตที่เหลือค้าง

-- ข้อ 5.3 ตรวจข้อมูลที่ไม่มีความสัมพันธ์ (LEFT JOIN ... IS NULL)
-- คำถาม: ค้นหารายการใบแจ้งหนี้ที่ค้างคา โดยหาว่าใบแจ้งหนี้ใดบ้างในระบบที่ตรวจแล้ว "ยังไม่เคยได้รับชำระเงินเข้ามาเลย" แม้แต่ครั้งเดียว (ไม่มีประวัติการจ่ายในตาราง payments)
SELECT 
    i.invoice_number AS "เลขที่ใบแจ้งหนี้ที่ยังไม่ชำระเงิน", 
    i.patient_id AS "รหัสผู้ป่วย", 
    i.net_amount AS "ยอดค้างชำระ (บาท)", 
    i.status AS "สถานะปัจจุบัน"
FROM invoices i
LEFT JOIN payments p ON i.invoice_id = p.invoice_id
WHERE p.payment_id IS NULL;
-- ผลที่คาดหวัง: แสดงรายการใบแจ้งหนี้จำนวน 6 ใบ (INV-2026-0002, INV-2026-0003, INV-2026-0007, INV-2026-0011, INV-2026-0015, INV-2026-0017) ที่ยังไม่มีการชำระเงินในระบบเลย
-- คำอธิบาย: ใช้ตรวจเช็กว่ายอดบิลใดที่ยังไม่ได้จ่ายเลยสักบาท เพื่อรายงานแผนกบัญชีสำหรับจัดทำจดหมายทวงถามหนี้สินค้างชำระต่อไป


